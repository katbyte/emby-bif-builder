#!/usr/bin/env bash
#
# Regenerates the source-build formula in katbyte/homebrew-tap for a released tag.
# Usage: TAG=v1.0.0 [TAP_DRY_RUN=1] HOMEBREW_TAP_GITHUB_TOKEN=... ./.scripts/update-homebrew-formula.sh
set -euo pipefail

TAG="${TAG:?set TAG to the release tag, e.g. v1.0.0}"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

echo "==> fetching source tarball for ${TAG}..."
curl -sSfL "https://github.com/katbyte/emby-bif-builder/archive/refs/tags/${TAG}.tar.gz" -o "$tmp/src.tar.gz"

# GitHub answers some missing tarballs with a web page rather than an error, and its hash would make a formula that never installs
tar -tzf "$tmp/src.tar.gz" > /dev/null 2>&1 || { echo "==> ${TAG} has no source tarball on GitHub yet" >&2; exit 1; }
SHA256="$(sha256sum "$tmp/src.tar.gz" | cut -d' ' -f1)"

cat > "$tmp/emby-bif-builder.rb" <<FORMULA
# typed: false
# frozen_string_literal: true

# This file is generated by the emby-bif-builder release workflow - do not edit by hand.
class EmbyBifBuilder < Formula
  desc "Gives Emby its preview pictures, cut from Jellyfin's thumbnails or built from the video"
  homepage "https://github.com/katbyte/emby-bif-builder"
  url "https://github.com/katbyte/emby-bif-builder/archive/refs/tags/${TAG}.tar.gz"
  sha256 "${SHA256}"
  license "GPL-3.0-only"
  head "https://github.com/katbyte/emby-bif-builder.git", branch: "main"

  depends_on "go" => :build

  def install
    # the program is ebb, not the module's name
    system "go", "build", *std_go_args(output: bin/"ebb", ldflags: "-s -w -X github.com/katbyte/go-kt/version.Version=${TAG} -X github.com/katbyte/go-kt/version.GitCommit=homebrew")
  end

  test do
    assert_match "${TAG}", shell_output("#{bin}/ebb version")
  end
end
FORMULA

if [ "${TAP_DRY_RUN:-0}" = "1" ]; then
  echo "==> dry run; generated formula:"
  cat "$tmp/emby-bif-builder.rb"
  exit 0
fi

: "${HOMEBREW_TAP_GITHUB_TOKEN:?set HOMEBREW_TAP_GITHUB_TOKEN to a token with push access to katbyte/homebrew-tap}"
echo "==> pushing formula to katbyte/homebrew-tap..."
git clone --depth 1 "https://x-access-token:${HOMEBREW_TAP_GITHUB_TOKEN}@github.com/katbyte/homebrew-tap.git" "$tmp/tap"
mkdir -p "$tmp/tap/Formula"
cp "$tmp/emby-bif-builder.rb" "$tmp/tap/Formula/emby-bif-builder.rb"
cd "$tmp/tap"
git config user.name "emby-bif-builder-release"
git config user.email "emby-bif-builder-release@katbyte.me"
git add Formula/emby-bif-builder.rb
git diff --cached --quiet && { echo "==> formula unchanged"; exit 0; }
git commit -m "emby-bif-builder ${TAG}"
git push
echo "==> done"
